import { type Element, enumLabel, normalizeName, typeDef } from '@atrium/schema';
import type { RequestContext } from '../auth/context';
import { notFound } from '../http/errors';
import type { Deps } from './deps';
import { ModelIndex } from './model-index';
import { bestMatch } from './search';
import { resolveState } from './store';
import { getWorkspace } from './workspace';

export function findService(index: ModelIndex, ref: string): Element | undefined {
  const direct = index.get(ref);
  if (direct) return direct;
  for (const t of [
    'application',
    'interface',
    'technology',
    'data_object',
    'capability',
  ] as const) {
    const byKey = index.byKey(t, ref);
    if (byKey) return byKey;
  }
  const n = normalizeName(ref);
  return (
    [...index.model.elements.values()].find((e) => normalizeName(e.name) === n) ??
    bestMatch(index, ref, ['application', 'interface'])
  );
}

/** Standards that apply to an element: linked directly, matching its technologies, or organisation-wide musts. */
export function applicableStandards(
  index: ModelIndex,
  el: Element,
): Array<{ standard: Element; why: string }> {
  const out = new Map<string, { standard: Element; why: string }>();
  for (const s of index.targets(el.id, 'governed_by').filter((x) => x.type === 'standard'))
    out.set(s.id, { standard: s, why: 'Linked directly' });
  // Technology names without their version: "PostgreSQL 12" → "postgresql".
  const techs = index
    .targets(el.id, 'uses')
    .map((t) => normalizeName(t.name).replace(/( \d[\w ]*)+$/, ''));
  for (const s of index.ofType('standard')) {
    if (out.has(s.id)) continue;
    const match = (s.attributes.match as string[] | undefined) ?? [];
    const hit = match.find((m) => {
      const base = normalizeName(m).replace(/( \d[\w ]*)+$/, '');
      return techs.some((t) => t === base);
    });
    if (hit) out.set(s.id, { standard: s, why: `Applies to ${hit.replace(/\s+\d.*$/, '')}` });
    else if (
      s.attributes.level === 'must' &&
      ['security', 'integration', 'data', 'cloud'].includes(s.attributes.category as string)
    ) {
      out.set(s.id, { standard: s, why: 'Applies to every service' });
    }
  }
  return [...out.values()].sort(
    (a, b) =>
      (a.standard.attributes.level === 'must' ? -1 : 1) -
      (b.standard.attributes.level === 'must' ? -1 : 1),
  );
}

const md = (s: string | null | undefined) => (s ?? '').replace(/\r?\n/g, ' ').trim();
const key = (e: Element) => (e.key ? ` (\`${e.key}\`)` : '');

/** Everything a person or coding agent needs to know about one service, as Markdown. */
export async function serviceContextMarkdown(
  deps: Deps,
  ctx: RequestContext,
  ref: string,
): Promise<{ element: Element; markdown: string }> {
  const state = await resolveState(deps.store, deps.sql, ctx, { includeDrafts: false });
  const index = new ModelIndex(state);
  const el = findService(index, ref);
  if (!el) throw notFound(`A service called "${ref}"`);
  const ws = await getWorkspace(deps.sql, deps.config.workspaceName);
  const lines: string[] = [];
  const domain = index.get(el.domainId);
  const teams = index.targets(el.id, 'owned_by');
  lines.push(`# ${el.name}: architecture context`, '');
  lines.push(
    `> Generated by Atrium${ws.name !== 'Atrium' ? ` (${ws.name})` : ''} on ${new Date().toISOString().slice(0, 10)}. The source of truth is ${deps.config.publicUrl}/e/${el.id}.`,
    '> Do not edit this file by hand. Change the model in Atrium, or propose a change with the `propose_change` tool or `atrium sync`.',
    '',
  );
  const facts = [
    el.key && `**Key:** \`${el.key}\``,
    `**Type:** ${typeDef(el.type).label}`,
    el.lifecycle && `**Lifecycle:** ${enumLabel(el.lifecycle)}`,
    el.health && `**Health:** ${enumLabel(el.health)}`,
    domain && `**Domain:** ${domain.name}`,
    el.owner && `**Owner:** ${el.owner}`,
    teams.length && `**Team:** ${teams.map((t) => t.name).join(', ')}`,
    `**Classification:** ${enumLabel(el.classification)}`,
    el.attributes.criticality &&
      `**Criticality:** ${enumLabel(el.attributes.criticality as string)}`,
    el.attributes.time && `**TIME:** ${enumLabel(el.attributes.time as string)}`,
  ].filter(Boolean);
  lines.push(facts.join(' · '), '');
  lines.push('## Purpose', '', md(el.description) || '_No description yet._', '');

  const caps = index.targets(el.id, 'supports');
  if (caps.length)
    lines.push('## Business capabilities it supports', '', ...caps.map((c) => `- ${c.name}`), '');

  const warn = (e: Element) => {
    const notes = [];
    if (e.lifecycle === 'phase_out' || e.lifecycle === 'retired')
      notes.push(`⚠ ${enumLabel(e.lifecycle).toLowerCase()}`);
    if (e.attributes.time === 'eliminate') notes.push('⚠ to be eliminated');
    const successor = index.sources(e.id, 'replaces')[0];
    if (successor) notes.push(`replaced by ${successor.name}${key(successor)}`);
    return notes.length ? ` (${notes.join(', ')})` : '';
  };
  const up = index.targets(el.id, 'depends_on');
  const down = index.sources(el.id, 'depends_on');
  if (up.length)
    lines.push(
      '## Depends on (upstream)',
      '',
      ...up.map((u) => `- ${u.name}${key(u)}${warn(u)}`),
      '',
    );
  if (down.length)
    lines.push(
      '## Used by (downstream)',
      '',
      '_Changing this service can affect:_',
      '',
      ...down.map((d) => `- ${d.name}${key(d)}`),
      '',
    );
  const sendsTo = index.targets(el.id, 'flows_to');
  const receivesFrom = index.sources(el.id, 'flows_to');
  if (sendsTo.length || receivesFrom.length) {
    lines.push('## Data flows', '');
    for (const t of sendsTo) lines.push(`- Sends data to ${t.name}${key(t)}`);
    for (const s of receivesFrom) lines.push(`- Receives data from ${s.name}${key(s)}`);
    lines.push('');
  }
  const provides = index.targets(el.id, 'exposes');
  const consumes = index.targets(el.id, 'consumes');
  if (provides.length || consumes.length) {
    lines.push('## Interfaces', '');
    if (provides.length) {
      lines.push('### Provides', '');
      for (const i of provides) {
        const users = index.sources(i.id, 'consumes').map((c) => c.name);
        lines.push(
          `- **${i.name}**${key(i)}: ${[enumLabel(i.attributes.protocol as string), enumLabel(i.attributes.frequency as string)].filter(Boolean).join(', ')}${i.attributes.docs ? `, docs: ${i.attributes.docs}` : ''}${users.length ? `. Used by ${users.join(', ')}` : ''}${warn(i)}`,
        );
      }
      lines.push('');
    }
    if (consumes.length) {
      lines.push('### Uses', '');
      for (const i of consumes) {
        const provider = index.sources(i.id, 'exposes')[0];
        lines.push(`- **${i.name}**${key(i)}${provider ? ` from ${provider.name}` : ''}${warn(i)}`);
      }
      lines.push('');
    }
  }
  const data = index.targets(el.id, 'stores');
  if (data.length) {
    lines.push(
      '## Data it manages',
      '',
      ...data.map(
        (d) =>
          `- ${d.name}: ${enumLabel(d.attributes.sensitivity as string) || 'sensitivity not set'}, ${enumLabel(d.classification).toLowerCase()}`,
      ),
      '',
    );
  }
  const techs = index.targets(el.id, 'uses');
  if (techs.length) {
    lines.push(
      '## Technology',
      '',
      '| Technology | Version | Radar | End of life |',
      '|---|---|---|---|',
    );
    const today = new Date().toISOString().slice(0, 10);
    for (const t of techs) {
      const eol = t.attributes.eol_date as string | undefined;
      lines.push(
        `| ${t.name} | ${t.attributes.version ?? ''} | ${enumLabel(t.attributes.radar as string) || 'Not rated'} | ${eol ? `${eol}${eol < today ? ' ⚠ past' : ''}` : ''} |`,
      );
    }
    lines.push('');
  }
  const standards = applicableStandards(index, el);
  if (standards.length) {
    lines.push('## Standards and guardrails', '');
    for (const { standard: s, why } of standards) {
      lines.push(
        `- **${(s.attributes.level as string)?.toUpperCase() ?? 'SHOULD'}: ${s.name}**: ${md((s.attributes.rule as string) || s.description)} _(${why})_`,
      );
    }
    lines.push('');
  }
  const decisions = [
    ...index.targets(el.id, 'governed_by').filter((d) => d.type === 'decision'),
    ...index.sources(el.id, 'governed_by').filter((d) => d.type === 'decision'),
  ];
  if (decisions.length) {
    lines.push('## Architecture decisions', '');
    for (const d of decisions)
      lines.push(
        `- **${d.name}** (${enumLabel(d.attributes.status as string) || 'status unknown'}${d.attributes.date ? `, ${d.attributes.date}` : ''}): ${md(d.attributes.decision as string) || md(d.description)}`,
      );
    lines.push('');
  }
  const principles = index.ofType('principle');
  if (principles.length)
    lines.push(
      '## Principles',
      '',
      ...principles.slice(0, 10).map((p) => `- **${p.name}**: ${md(p.description)}`),
      '',
    );
  if (el.healthReasons.length)
    lines.push('## Known risks', '', ...el.healthReasons.map((r) => `- ${r}`), '');
  const initiatives = index.sources(el.id, 'impacts');
  if (initiatives.length)
    lines.push(
      '## Planned change',
      '',
      ...initiatives.map(
        (i) =>
          `- ${i.name} (${enumLabel(i.attributes.status as string)}, ${i.attributes.start_date ?? '?'} to ${i.attributes.end_date ?? '?'})`,
      ),
      '',
    );
  lines.push(
    '## Keeping this up to date',
    '',
    '- Coding agents: call `check_against_standards` before proposing a design, and `propose_change` when the code changes what is described here.',
    '- CI: keep `atrium.yaml` in the repository and run `atrium sync` on merge.',
    '',
  );
  return { element: el, markdown: lines.join('\n') };
}
