function toElement(s: AppSpec): SeedElement {
  const el: SeedElement = {
    ref: s.ref,
    type: 'application',
    name: s.name,
    key: s.key,
    lifecycle: s.lifecycle,
    classification: s.classification ?? 'internal',
    attributes: compact({
      vendor: s.vendor,
      product: s.product,
      version: s.version,
      hosting: s.hosting,
      annual_cost: s.cost,
      users: s.users,
      criticality: s.criticality,
      time: s.time,
      business_fit: s.businessFit,
      technical_fit: s.technicalFit,
      url: s.url,
    }),
  };
  if (s.description) el.description = s.description;
  if (s.domain) el.domain = s.domain;
  if (s.owner) el.owner = s.owner;
  if (s.dates) el.lifecycleDates = s.dates;
  if (s.tags) el.tags = s.tags;
  if (s.cmdb) el.externalIds = { cmdb: s.cmdb };
  return el;
}

export const applications: SeedElement[] = specs.map(toElement);

/** owned_by (app → team), supports (app → capability / process) and uses (app → technology). */
export const applicationRelations: SeedRelation[] = specs.flatMap((s) => [
  ...(s.team ? [rel('owned_by', s.ref, s.team)] : []),
  ...fanOut('supports', s.ref, s.supports ?? []),
  ...fanOut('uses', s.ref, s.uses ?? []),
]);
