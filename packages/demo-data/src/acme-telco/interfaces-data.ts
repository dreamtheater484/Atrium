export const interfaces: SeedElement[] = interfaceSpecs.map((i) => ({
  ref: i.ref,
  type: 'interface',
  name: i.name,
  key: i.key,
  description: i.description,
  owner: i.owner,
  lifecycle: i.lifecycle,
  classification: 'internal',
  attributes: {
    protocol: i.protocol,
    frequency: i.frequency,
    ...(i.docs ? { docs: `${DOCS}/${i.key}` } : {}),
  },
}));

/** exposes (provider → interface) and consumes (consumer → interface). */
export const interfaceRelations: SeedRelation[] = interfaceSpecs.flatMap((i) => [
  rel('exposes', i.provider, i.ref),
  ...fanIn('consumes', i.consumers, i.ref),
]);

